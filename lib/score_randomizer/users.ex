defmodule ScoreRandomizer.Users do
  @moduledoc """
  The Users context.
  """
  alias ScoreRandomizer.Repo
  alias ScoreRandomizer.Users.User

  import Ecto.Query, warn: false

  @doc """
  Returns the list of users.

  ## Examples

      iex> list_users()
      [%User{}, ...]

  """
  def list_users do
    Repo.all(User)
  end

  @doc """
  Gets a single user.

  Raises `Ecto.NoResultsError` if the User does not exist.

  ## Examples

      iex> get_user!(123)
      %User{}

      iex> get_user!(456)
      ** (Ecto.NoResultsError)

  """
  def get_user!(id), do: Repo.get!(User, id)

  @doc """
  Creates a user.

  ## Examples

      iex> create_user(%{field: value})
      {:ok, %User{}}

      iex> create_user(%{field: bad_value})
      {:error, %Ecto.Changeset{}}

  """
  def create_user(attrs \\ %{}) do
    %User{}
    |> User.changeset(attrs)
    |> Repo.insert()
  end

  @doc """
  Create Multiple users, an optional value can be passed
  to change the number of users. The default value is 1_000_000

  ## Examples
      iex> create_multiple_users()
      {:ok,[%User{}, ...] }

      iex> create_multiple_users()
      {:error, :message}
  """

  def create_multiple_users(number \\ 1_000_000) do
    time_now = DateTime.utc_now()

    %{points: 0, inserted_at: time_now, updated_at: time_now}
    |> List.duplicate(number)
    |> Enum.chunk_every(15_000)
    |> Enum.each(&Repo.insert_all(User, &1))
  end

  @doc """
  Updates a user.

  ## Examples

      iex> update_user(user, %{field: new_value})
      {:ok, %User{}}

      iex> update_user(user, %{field: bad_value})
      {:error, %Ecto.Changeset{}}

  """
  def update_user(%User{} = user, attrs) do
    user
    |> User.changeset(attrs)
    |> Repo.update()
  end

  @doc """
  Deletes a user.

  ## Examples

      iex> delete_user(user)
      {:ok, %User{}}

      iex> delete_user(user)
      {:error, %Ecto.Changeset{}}

  """
  def delete_user(%User{} = user) do
    Repo.delete(user)
  end

  @doc """
  Returns an `%Ecto.Changeset{}` for tracking user changes.

  ## Examples

      iex> change_user(user)
      %Ecto.Changeset{data: %User{}}

  """
  def change_user(%User{} = user, attrs \\ %{}) do
    User.changeset(user, attrs)
  end
end
